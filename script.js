const root = document.documentElement;
const header = document.querySelector(".site-header");
const navToggle = document.querySelector(".nav-toggle");
const languageButtons = document.querySelectorAll("[data-language]");

function setLanguage(language) {
  const chosenLanguage = translations[language] ? language : "en";
  const copy = translations[chosenLanguage];

  root.lang = chosenLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = copy[element.dataset.i18n];
    if (translation !== undefined) element.textContent = translation;
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const translation = copy[element.dataset.i18nContent];
    if (translation !== undefined) element.setAttribute("content", translation);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const translation = copy[element.dataset.i18nAlt];
    if (translation !== undefined) element.setAttribute("alt", translation);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const translation = copy[element.dataset.i18nAria];
    if (translation !== undefined) element.setAttribute("aria-label", translation);
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === chosenLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (navToggle) {
    const isOpen = header.classList.contains("is-menu-open");
    navToggle.setAttribute("aria-label", isOpen ? copy.closeNavigation : copy.openNavigation);
  }

  try {
    localStorage.setItem("six-chicks-language", chosenLanguage);
  } catch {
    // The page still works when browser storage is unavailable.
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

if (navToggle) {
  navToggle.addEventListener("click", () => {
    const isOpen = header.classList.toggle("is-menu-open");
    navToggle.setAttribute("aria-expanded", String(isOpen));
    navToggle.setAttribute(
      "aria-label",
      isOpen ? translations[root.lang].closeNavigation : translations[root.lang].openNavigation
    );
  });
}

document.querySelectorAll(".primary-nav a").forEach((link) => {
  link.addEventListener("click", () => {
    header.classList.remove("is-menu-open");
    navToggle?.setAttribute("aria-expanded", "false");
    if (navToggle) navToggle.setAttribute("aria-label", translations[root.lang].openNavigation);
  });
});

let savedLanguage = "en";
try {
  savedLanguage = localStorage.getItem("six-chicks-language") || "en";
} catch {
  // Default to English when browser storage is unavailable.
}
setLanguage(savedLanguage);
